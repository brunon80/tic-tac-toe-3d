export const THEME_PRESETS: readonly ThemePalette[] = PRESETS
export const DEFAULT_THEME_ID = 'neon-violet'

export function getPreset(id: string): ThemePalette {
  return PRESETS.find((p) => p.id === id) ?? PRESETS[0]
}

export function presetOptions(): { id: string; label: string; description: string; swatch: readonly string[] }[] {
  return PRESETS.map((p) => ({
    id: p.id,
    label: p.label,
    description: p.description,
    swatch: [p.x, p.o, p.accent, p.tile],
  }))
}

/** A "shuffle colours" variant: random accent pair applied on top of a preset. */
export function randomThemeVariant(base: ThemePalette, rng: () => number = Math.random): ThemePalette {
  const hue = Math.floor(rng() * 360)
  const secondaryHue = (hue + 140 + Math.floor(rng() * 80)) % 360
  const accent = hslToHex(hue, 78, 58)
  return applyCustomColors(base, {
    accent,
    x: hslToHex(hue, 85, 62),
    o: hslToHex(secondaryHue, 80, 60),
    win: hslToHex((hue + 60) % 360, 85, 66),
    gridLine: lighten(accent, 0.12),
  })
}

export function resolveTheme(settings: ThemeSettings): ThemePalette {
  const preset = getPreset(settings.presetId)
  const keys = Object.keys(settings.colors)
  if (keys.length === 0) return preset
  return applyCustomColors(preset, settings.colors)
}
